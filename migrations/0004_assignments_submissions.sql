-- 0004_assignments_submissions.sql
-- ASSIGNMENTS belong to a course (the syllabus), not to a cohort -- every January intake
-- of "Systems Programming" hands in the same exercise 3.
-- SUBMISSIONS is the fact table: one row per attempt.  This is the table that grows to
-- 5,000,000 rows in the seed, and it is where every performance lesson in this repo lives.

CREATE TYPE assignment_kind   AS ENUM ('quiz', 'coding', 'essay', 'project');
CREATE TYPE submission_status AS ENUM ('submitted', 'graded', 'late', 'plagiarised');

CREATE TABLE assignments (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id      integer         NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    position       smallint        NOT NULL,
    title          text            NOT NULL,
    kind           assignment_kind NOT NULL,
    max_score      smallint        NOT NULL,
    due_offset_days smallint       NOT NULL,
    is_optional    boolean         NOT NULL DEFAULT false,

    CONSTRAINT assignments_position_uk  UNIQUE (course_id, position),
    CONSTRAINT assignments_max_score_ck CHECK (max_score BETWEEN 1 AND 1000),
    CONSTRAINT assignments_offset_ck    CHECK (due_offset_days >= 0)
);

CREATE TABLE submissions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id integer           NOT NULL REFERENCES enrollments (id) ON DELETE CASCADE,
    assignment_id integer           NOT NULL REFERENCES assignments (id) ON DELETE CASCADE,
    attempt_no    smallint          NOT NULL DEFAULT 1,
    status        submission_status NOT NULL DEFAULT 'submitted',
    score         numeric(6,2),
    submitted_at  timestamptz       NOT NULL,
    graded_at     timestamptz,
    runtime_ms    integer,

    CONSTRAINT submissions_attempt_uk  UNIQUE (enrollment_id, assignment_id, attempt_no),
    CONSTRAINT submissions_attempt_ck  CHECK (attempt_no BETWEEN 1 AND 50),
    CONSTRAINT submissions_score_ck    CHECK (score IS NULL OR score >= 0),
    CONSTRAINT submissions_graded_ck   CHECK (graded_at IS NULL OR graded_at >= submitted_at),
    -- A graded submission must carry a score.  Encoding this here means no query ever has
    -- to defend against the "graded but score IS NULL" case, because it cannot exist.
    CONSTRAINT submissions_status_ck   CHECK (status <> 'graded' OR score IS NOT NULL)
);
