-- 0005_mentor_sessions.sql
-- One-to-one mentoring calls attached to an enrollment.
--
-- Modelling compromise worth naming out loud: mentors are `learners` with is_mentor=true
-- rather than their own table, because the brief fixes the schema at eight tables.  On a
-- real platform mentors would get a `mentors` table (they have pay rates, contracts and
-- availability that learners do not).  The upside of the compromise is that it gives us a
-- genuine SELF JOIN to teach: learners joined to learners through mentor_sessions.

CREATE TYPE session_status AS ENUM ('scheduled', 'completed', 'no_show', 'cancelled');

CREATE TABLE mentor_sessions (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id  integer        NOT NULL REFERENCES enrollments (id) ON DELETE CASCADE,
    mentor_id      integer        NOT NULL REFERENCES learners (id) ON DELETE RESTRICT,
    scheduled_at   timestamptz    NOT NULL,
    duration_min   smallint       NOT NULL,
    status         session_status NOT NULL DEFAULT 'scheduled',
    learner_rating smallint,
    notes          text,

    CONSTRAINT mentor_sessions_duration_ck CHECK (duration_min BETWEEN 15 AND 240),
    CONSTRAINT mentor_sessions_rating_ck   CHECK (learner_rating IS NULL OR learner_rating BETWEEN 1 AND 5),
    -- Only a completed session can carry a rating.
    CONSTRAINT mentor_sessions_rating_status_ck CHECK (learner_rating IS NULL OR status = 'completed')
);
