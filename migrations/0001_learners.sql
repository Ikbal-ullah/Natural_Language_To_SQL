-- 0001_learners.sql
-- The person who learns. Root entity: almost every fact in the system hangs off a learner.
--
-- Design notes for the reader (see LEARN.md "Primary and foreign keys"):
--  * `id` is a SURROGATE key: a meaningless integer whose only job is to be stable.
--    We could have used `email` as the primary key (a NATURAL key). We did not, because
--    people change their email address, and a primary key that changes forces you to
--    rewrite every row that references it.
--  * `email` still gets a UNIQUE constraint. Uniqueness is a business rule; being the
--    primary key is a storage decision. They are different questions.

CREATE TYPE learner_status AS ENUM ('active', 'paused', 'churned', 'banned');

CREATE TABLE learners (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           text           NOT NULL,
    full_name       text           NOT NULL,
    country_code    char(2)        NOT NULL,
    timezone        text           NOT NULL DEFAULT 'UTC',
    status          learner_status NOT NULL DEFAULT 'active',
    is_mentor       boolean        NOT NULL DEFAULT false,
    signup_ts       timestamptz    NOT NULL DEFAULT now(),
    last_active_ts  timestamptz,

    CONSTRAINT learners_email_uk       UNIQUE (email),
    CONSTRAINT learners_email_shape_ck CHECK (email LIKE '%@%.%'),
    CONSTRAINT learners_country_ck     CHECK (country_code ~ '^[A-Z]{2}$'),
    -- You cannot have been active before you existed.
    CONSTRAINT learners_activity_ck    CHECK (last_active_ts IS NULL OR last_active_ts >= signup_ts)
);
