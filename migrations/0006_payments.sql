-- 0006_payments.sql
-- Money.  Every amount is an integer number of minor units (cents) -- see courses.
--
-- `enrollment_id` is NULLable on purpose: a learner can pay for a subscription or a
-- credit pack that is not tied to a single enrollment.  A NULLable foreign key is the
-- correct way to model "this relationship is optional"; the alternative people reach for
-- -- a magic sentinel like enrollment_id = 0 -- defeats the foreign key and forces every
-- query to remember the sentinel.

CREATE TYPE payment_status AS ENUM ('pending', 'succeeded', 'failed', 'refunded');
CREATE TYPE payment_method AS ENUM ('card', 'bank_transfer', 'paypal', 'employer_invoice');

CREATE TABLE payments (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id           integer        NOT NULL REFERENCES learners (id) ON DELETE RESTRICT,
    enrollment_id        integer        REFERENCES enrollments (id) ON DELETE SET NULL,
    amount_cents         integer        NOT NULL,
    currency             char(3)        NOT NULL DEFAULT 'USD',
    status               payment_status NOT NULL DEFAULT 'pending',
    method               payment_method NOT NULL,
    created_at           timestamptz    NOT NULL DEFAULT now(),
    settled_at           timestamptz,
    refunded_amount_cents integer       NOT NULL DEFAULT 0,
    external_ref         text,

    CONSTRAINT payments_external_ref_uk UNIQUE (external_ref),
    CONSTRAINT payments_amount_ck       CHECK (amount_cents > 0),
    CONSTRAINT payments_currency_ck     CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT payments_refund_ck       CHECK (refunded_amount_cents BETWEEN 0 AND amount_cents),
    CONSTRAINT payments_settled_ck      CHECK (settled_at IS NULL OR settled_at >= created_at),
    CONSTRAINT payments_refund_status_ck CHECK (refunded_amount_cents = 0 OR status = 'refunded')
);
