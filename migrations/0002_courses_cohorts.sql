-- 0002_courses_cohorts.sql
-- A COURSE is the syllabus (stable, reusable).  A COHORT is one scheduled run of that
-- course with a start date, a capacity and a mentor.  Splitting them is textbook 3NF:
-- the course title depends on the course, not on the particular January intake.  Keeping
-- them in one table would repeat the title, subject and price once per intake, and a
-- retitle would have to be applied to every intake row or the table would contradict itself.

CREATE TYPE course_difficulty AS ENUM ('beginner', 'intermediate', 'advanced');
CREATE TYPE cohort_status     AS ENUM ('scheduled', 'running', 'finished', 'cancelled');

CREATE TABLE courses (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             text              NOT NULL,
    title            text              NOT NULL,
    subject          text              NOT NULL,
    difficulty       course_difficulty NOT NULL,
    -- Money is stored as an integer number of cents.  Never float: 0.1 + 0.2 <> 0.3 in
    -- binary floating point, and a rounding error in a payments table is a real bug.
    list_price_cents integer           NOT NULL,
    duration_weeks   smallint          NOT NULL,
    is_active        boolean           NOT NULL DEFAULT true,
    published_at     timestamptz       NOT NULL DEFAULT now(),

    CONSTRAINT courses_slug_uk     UNIQUE (slug),
    CONSTRAINT courses_price_ck    CHECK (list_price_cents >= 0),
    CONSTRAINT courses_duration_ck CHECK (duration_weeks BETWEEN 1 AND 52)
);

CREATE TABLE cohorts (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id    integer       NOT NULL REFERENCES courses (id) ON DELETE RESTRICT,
    name         text          NOT NULL,
    starts_on    date          NOT NULL,
    ends_on      date          NOT NULL,
    capacity     smallint      NOT NULL,
    status       cohort_status NOT NULL DEFAULT 'scheduled',
    mentor_id    integer       REFERENCES learners (id) ON DELETE SET NULL,

    CONSTRAINT cohorts_name_uk    UNIQUE (course_id, name),
    CONSTRAINT cohorts_dates_ck   CHECK (ends_on > starts_on),
    CONSTRAINT cohorts_capacity_ck CHECK (capacity BETWEEN 1 AND 1000),

    -- This UNIQUE constraint looks redundant -- `id` is already the primary key, so
    -- (id, course_id) is trivially unique.  It exists purely so that another table can
    -- point a COMPOSITE foreign key at it.  See 0003_enrollments.sql, which uses it to
    -- make our one deliberate denormalisation impossible to corrupt.
    CONSTRAINT cohorts_id_course_uk UNIQUE (id, course_id)
);
